import { describe, expect, it } from "vitest";
import {
  countHeaderRules,
  headersFor,
  mergeHeadersFile,
  parseHeadersFile,
  renderHeaderRules,
  toHeaderRules,
} from "./static-headers.js";

function routes(entries: Record<string, Record<string, string>>) {
  return new Map(
    Object.entries(entries).map(([path, headers]) => [
      path,
      { headers: new Headers(headers) },
    ])
  );
}

describe("toHeaderRules", () => {
  it("makes one rule per page with headers and skips the rest", () => {
    const rules = toHeaderRules(
      routes({
        "/": { "content-security-policy": "default-src 'self'" },
        "/about": {},
      })
    );
    expect(rules).toEqual([
      {
        pattern: "/",
        headers: [["content-security-policy", "default-src 'self'"]],
      },
    ]);
  });
});

describe("toHeaderRules details", () => {
  const input = routes({
    "/": { "content-type": "text/html", "x-a": "1" },
    "/about": { "x-a": "1" },
  });

  it("drops headers that describe the body", () => {
    expect(toHeaderRules(input)[0]?.headers).toEqual([["x-a", "1"]]);
  });

  it("adds a trailing slash for the directory format, except for the root", () => {
    expect(
      toHeaderRules(input, { trailingSlash: true }).map((rule) => rule.pattern)
    ).toEqual(["/", "/about/"]);
  });
});

describe("renderHeaderRules", () => {
  it("renders the _headers format", () => {
    expect(
      renderHeaderRules([
        {
          pattern: "/",
          headers: [
            ["x-a", "1"],
            ["x-b", "2"],
          ],
        },
        { pattern: "/docs", headers: [["x-c", "3"]] },
      ])
    ).toBe("/\n  x-a: 1\n  x-b: 2\n\n/docs\n  x-c: 3");
  });
});

describe("mergeHeadersFile", () => {
  const rules = [
    { pattern: "/", headers: [["x-a", "1"]] as [string, string][] },
  ];

  it("keeps the user's rules and appends the generated ones", () => {
    const merged = mergeHeadersFile("/*\n  X-Frame-Options: DENY\n", rules);
    expect(merged.startsWith("/*\n  X-Frame-Options: DENY\n\n#")).toBe(true);
    expect(merged.trimEnd().endsWith("/\n  x-a: 1")).toBe(true);
  });

  it("replaces the generated part of an earlier build", () => {
    const first = mergeHeadersFile("/*\n  X-Frame-Options: DENY\n", rules);
    const second = mergeHeadersFile(first, [
      { pattern: "/new", headers: [["x-b", "2"]] },
    ]);
    expect(second).toContain("/new");
    expect(second).not.toContain("x-a: 1");
    expect(second.match(/Generated by/g)).toHaveLength(1);
  });

  it("writes nothing when there are no rules and no file", () => {
    expect(mergeHeadersFile(undefined, [])).toBe("");
  });
});

describe("countHeaderRules", () => {
  it("counts path lines only", () => {
    expect(countHeaderRules("# c\n/a\n  x: 1\n\n/b\n  y: 2\n")).toBe(2);
  });
});

describe("parseHeadersFile and headersFor", () => {
  const rules = parseHeadersFile(
    "/*\n  X-Frame-Options: DENY\n\n/blog/:slug\n  Cache-Control: max-age=60\n\n/docs/*\n  X-Docs: yes\n  ! X-Frame-Options\n"
  );

  it("applies splats, placeholders and exact paths", () => {
    expect(headersFor(rules, "/")).toEqual([["x-frame-options", "DENY"]]);
    expect(headersFor(rules, "/blog/hello")).toEqual([
      ["x-frame-options", "DENY"],
      ["cache-control", "max-age=60"],
    ]);
    expect(headersFor(rules, "/docs/a/b")).toContainEqual(["x-docs", "yes"]);
  });

  it("joins repeated headers like Pages", () => {
    const joined = parseHeadersFile("/*\n  X-A: 1\n/x\n  X-A: 2\n");
    expect(headersFor(joined, "/x")).toEqual([["x-a", "1, 2"]]);
  });
});
