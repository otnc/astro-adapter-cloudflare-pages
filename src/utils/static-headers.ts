/** Pages rejects a `_headers` file with more rules than this. */
export const PAGES_HEADER_RULE_LIMIT = 100;

const GENERATED_MARKER = "# Generated by astro-adapter-cloudflare-pages";

type RouteHeaders = Map<string, { headers: Headers }>;

export interface HeaderRule {
  /** A Pages path pattern: exact, with `:placeholder` segments, or ending in `*`. */
  pattern: string;
  headers: Array<[name: string, value: string]>;
}

// Describe the response body, which Pages sets itself; a fixed value could drop the charset.
const BODY_HEADERS = new Set([
  "content-type",
  "content-length",
  "content-encoding",
]);

interface HeaderRuleOptions {
  /** Pages serves `about/index.html` at `/about/` and redirects `/about` to it, which is what Astro's `directory` build format produces. */
  trailingSlash: boolean;
}

/**
 * Builds `_headers` rules from the headers Astro computed for static pages, such as the Content-Security-Policy of `security.csp`. Pages that have no headers produce no rule.
 */
export function toHeaderRules(
  routeToHeaders: RouteHeaders,
  options: HeaderRuleOptions = { trailingSlash: false }
): HeaderRule[] {
  const rules: HeaderRule[] = [];
  for (const [pathname, { headers }] of routeToHeaders) {
    const entries = [...headers]
      .filter(([name]) => !BODY_HEADERS.has(name.toLowerCase()))
      .map(([name, value]) => [name, value] as [string, string]);
    if (entries.length === 0) continue;
    const pattern =
      options.trailingSlash && pathname !== "/" && !pathname.endsWith("/")
        ? `${pathname}/`
        : pathname;
    rules.push({ pattern, headers: entries });
  }
  return rules;
}

/** Renders rules in the `_headers` format: a path line, then one indented `Name: value` line per header. */
export function renderHeaderRules(rules: HeaderRule[]): string {
  return rules
    .map(
      ({ pattern, headers }) =>
        `${pattern}\n${headers.map(([name, value]) => `  ${name}: ${value}`).join("\n")}`
    )
    .join("\n\n");
}

/**
 * Appends the generated rules to an existing `_headers` file (for example one copied from `public/`), replacing the generated part of an earlier build, so the user's own rules stay untouched.
 */
export function mergeHeadersFile(
  existing: string | undefined,
  rules: HeaderRule[]
): string {
  const own = (existing ?? "").split(GENERATED_MARKER)[0]!.trimEnd();
  if (rules.length === 0) return own === "" ? "" : `${own}\n`;
  const generated = `${GENERATED_MARKER}\n${renderHeaderRules(rules)}`;
  return `${own === "" ? "" : `${own}\n\n`}${generated}\n`;
}

/** Counts the rules of a `_headers` file: every non-indented, non-comment line that starts a path. */
export function countHeaderRules(content: string): number {
  return content
    .split(/\r?\n/)
    .filter(
      (line) => line.trim() !== "" && !/^\s/.test(line) && !line.startsWith("#")
    ).length;
}

/** Parses a `_headers` file into rules. Headers starting with `!` (removals) are ignored. */
export function parseHeadersFile(content: string): HeaderRule[] {
  const rules: HeaderRule[] = [];
  let current: HeaderRule | undefined;
  for (const raw of content.split(/\r?\n/)) {
    if (raw.trim() === "" || raw.trim().startsWith("#")) continue;
    if (!/^\s/.test(raw)) {
      current = { pattern: raw.trim(), headers: [] };
      rules.push(current);
      continue;
    }
    const separator = raw.indexOf(":");
    if (!current || separator === -1) continue;
    const name = raw.slice(0, separator).trim();
    if (name.startsWith("!")) continue;
    current.headers.push([name, raw.slice(separator + 1).trim()]);
  }
  return rules;
}

function matches(pattern: string, pathname: string): boolean {
  const source = pattern
    .replace(/[.+?^${}()|[\]\\]/g, "\\$&")
    .replace(/:[A-Za-z]\w*/g, "[^/]+")
    .replace(/\*/g, ".*");
  return new RegExp(`^${source}$`).test(pathname);
}

/** The headers that apply to a path: those of every matching rule, in file order, joined as Pages does. */
export function headersFor(
  rules: HeaderRule[],
  pathname: string
): Array<[name: string, value: string]> {
  const merged = new Map<string, string>();
  for (const rule of rules) {
    if (!matches(rule.pattern, pathname)) continue;
    for (const [name, value] of rule.headers) {
      const key = name.toLowerCase();
      const previous = merged.get(key);
      merged.set(key, previous === undefined ? value : `${previous}, ${value}`);
    }
  }
  return [...merged];
}
