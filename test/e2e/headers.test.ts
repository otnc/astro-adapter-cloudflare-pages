import { readFileSync } from "node:fs";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
  astroMajors,
  buildProject,
  packAdapter,
  prepareProject,
  startPagesDev,
  type PagesServer,
} from "./harness.js";

const tarball = packAdapter();

describe.each(astroMajors())(
  "Astro %i: static headers (headers fixture)",
  (major) => {
    let dir: string;
    let server: PagesServer;

    beforeAll(async () => {
      dir = prepareProject(major, "headers", tarball);
      buildProject(dir);
      server = await startPagesDev(dir, 8840 + major);
    });

    afterAll(() => {
      server?.stop();
    });

    it("writes the generated rules after the rules from public/_headers", () => {
      const headers = readFileSync(join(dir, "dist", "_headers"), "utf-8");
      expect(headers.startsWith("/*\n  X-Custom-Header: from-public")).toBe(
        true
      );
      expect(headers).toContain(
        "# Generated by astro-adapter-cloudflare-pages"
      );
      // The directory build format serves /about/ (index.html), and /about redirects to it.
      expect(headers).toMatch(/\/about\/\n\s+content-security-policy: /i);
      expect(headers).not.toMatch(/content-type/i);
    });

    it("sends the Content-Security-Policy of prerendered pages from the static files", async () => {
      const response = await fetch(`${server.url}/about`);
      expect(response.status).toBe(200);
      expect(response.headers.get("content-security-policy")).toContain(
        "script-src"
      );
      expect(response.headers.get("x-custom-header")).toBe("from-public");
      expect(await response.text()).not.toContain("http-equiv");
    });

    it("keeps the policy on on-demand pages", async () => {
      const response = await fetch(`${server.url}/ssr`);
      expect(response.headers.get("content-security-policy")).toContain(
        "script-src"
      );
    });
  }
);
